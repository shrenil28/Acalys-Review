import type { PlannerScenario } from "./scenario.js";

/**
 * The planner corpus.
 *
 * Small repositories where the required context is known by construction. Each
 * `because` is the argument for why a reviewer cannot do without that item — if
 * one cannot be written convincingly, the requirement is wrong and the scenario
 * is measuring a preference rather than a need.
 *
 * Deliberately small and hand-built rather than sampled from real pull
 * requests. A real PR's "required context" is a judgement call; these are
 * constructed so the answer is not.
 */

const pad = (lines: number) =>
  Array.from(
    { length: lines },
    (_unused, index) => `// filler ${String(index)}`,
  ).join("\n");

