import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { describe, expect, it } from "vitest";

import {
  BASELINE_VERSION,
  MIN_STABILITY,
  PLANNER_CORPUS,
  buildBaseline,
  compareBaseline,
  computeMetrics,
  contextSimilarity,
  evaluate,
  runScenario,
  summarize,
  type PlannerBaseline,
} from "../src/eval/index.js";

/**
 * The planner eval.
 *
 * `planner-scenarios.test.ts` asserts that particular files appear. This file
 * turns the same corpus into *numbers*, because a boolean cannot answer the
 * question that matters after P1-G lands:
 *
 *     the reviewer missed a bug — did the model fail despite seeing the
 *     required context, or did the planner never supply it?
 *
 * Invariants are absolute; trends are compared to a committed baseline. See
 * `src/eval/baseline.ts` for why those two are judged differently.
 */

const stored = JSON.parse(
  readFileSync(
    fileURLToPath(new URL("../eval/planner-baseline.json", import.meta.url)),
    "utf8",
  ),
) as PlannerBaseline;

const { report, contexts } = evaluate(PLANNER_CORPUS);
const byId = new Map(
  report.scenarios.map((metrics) => [metrics.scenarioId, metrics]),
);

describe("planner eval — invariants", () => {
  // Fail-closed. If the corpus import silently resolved to nothing, every
  // assertion below would pass vacuously and the eval would report health it
  // never measured.
  it("actually ran the corpus", () => {
    expect(PLANNER_CORPUS.length).toBeGreaterThanOrEqual(8);
    expect(report.scenarios).toHaveLength(PLANNER_CORPUS.length);
    expect(report.scenarios.every((m) => m.suppliedItems > 0)).toBe(true);
  });

  it.each(PLANNER_CORPUS.map((scenario) => [scenario.id, scenario] as const))(
    "%s supplies every required item",
    (id, scenario) => {
      const metrics = byId.get(id);
      expect(metrics).toBeDefined();
      if (metrics === undefined) return;

      // The `because` of each missing requirement, so a failure states its own
      // cause rather than printing a path.
      const reasons = scenario.required
        .filter((requirement) =>
          metrics.missingRequired.includes(
            requirement.symbol === undefined
              ? requirement.path
              : `${requirement.path}#${requirement.symbol}`,
          ),
        )
        .map((requirement) => `${requirement.path}: ${requirement.because}`);

      expect(reasons).toEqual([]);
      expect(metrics.requiredContextRecall).toBe(1);
    },
  );

  it("admits nothing forbidden", () => {
    expect(report.leaks).toEqual([]);
  });

  it("supplies every declared instruction", () => {
    expect(report.instructionCoverage).toBe(1);
  });

  it("supplies required symbols as symbols, not as whole files that contain them", () => {
    expect(report.relevantSymbolCoverage).toBe(1);
  });

  it("selects equivalent context for equivalent revisions", () => {
    const pairs = PLANNER_CORPUS.filter((s) => s.equivalentTo !== undefined);
    expect(pairs.length).toBeGreaterThan(0);

    for (const scenario of pairs) {
      const left = contexts.get(scenario.id);
      const right = contexts.get(scenario.equivalentTo ?? "");
      expect(left).toBeDefined();
      expect(right).toBeDefined();
      if (left === undefined || right === undefined) continue;
      expect(contextSimilarity(left, right)).toBeGreaterThanOrEqual(
        MIN_STABILITY,
      );
    }
  });
});

describe("planner eval — baseline", () => {
  it("was generated by the current metric definitions", () => {
    expect(stored.version).toBe(BASELINE_VERSION);
  });

  it("has not drifted", () => {
    const drift = compareBaseline(stored, buildBaseline(PLANNER_CORPUS));

    // Printed as a table rather than a boolean: the point of the baseline is
    // that a planner change produces a reviewable claim about what moved.
    expect(
      drift.map(
        (entry) =>
          `${entry.scenarioId}.${entry.metric}: ${String(entry.baseline)} → ${String(entry.current)}`,
      ),
    ).toEqual([]);
  });

  it("regenerates identically — the eval is deterministic", () => {
    expect(buildBaseline(PLANNER_CORPUS)).toEqual(
      buildBaseline(PLANNER_CORPUS),
    );
  });
});

describe("planner metrics — the metrics themselves detect what they claim to", () => {
  // A metric that cannot go wrong measures nothing. Each case below breaks the
  // scenario, not the planner, and asserts the metric notices.

  const base = PLANNER_CORPUS[0];
  if (base === undefined) throw new Error("corpus is empty");

  it("recall drops when a required item is genuinely absent", () => {
    const metrics = computeMetrics(
      {
        ...base,
        required: [
          ...base.required,
          { path: "src/nonexistent.ts", because: "planted absence" },
        ],
      },
      runScenario(base),
    );

    expect(metrics.requiredContextRecall).toBeLessThan(1);
    expect(metrics.missingRequired).toContain("src/nonexistent.ts");
  });

  it("symbol coverage drops when the file is supplied but the symbol is not", () => {
    const metrics = computeMetrics(
      {
        ...base,
        required: [
          {
            path: base.changed[0]?.path ?? "",
            symbol: "noSuchSymbol",
            because: "planted",
          },
        ],
      },
      runScenario(base),
    );

    expect(metrics.relevantSymbolCoverage).toBeLessThan(1);
  });

  it("instruction coverage drops when a declared instruction never arrives", () => {
    const context = runScenario(base);
    const metrics = computeMetrics(
      {
        ...base,
        instructions: [{ path: "UNSUPPLIED.md", content: "never planned" }],
      },
      context,
    );

    expect(metrics.instructionCoverage).toBe(0);
  });

  it("a leak is reported when a forbidden path is admitted", () => {
    const changedPath = base.changed[0]?.path ?? "";
    const metrics = computeMetrics(
      {
        ...base,
        forbidden: [
          {
            path: changedPath,
            because: "planted — the diff is always supplied",
          },
        ],
      },
      runScenario(base),
    );

    expect(metrics.forbiddenAdmitted).toContain(changedPath);
    expect(summarize([metrics]).leaks).toEqual([base.id]);
  });

  it("truncation is visible when the budget forces excerpts", () => {
    // A file large enough that the budget cannot hold it, with enough room left
    // for the assembler to excerpt rather than drop. The corpus itself is
    // deliberately tiny, so left to itself it would report a truncation rate of
    // zero forever — a metric that can never move is one nobody can trust.
    const big = [
      "export function huge(): number {",
      ...Array.from(
        { length: 400 },
        (_unused, index) => `  const v${String(index)} = ${String(index)};`,
      ),
      "  return 0;",
      "}",
    ].join("\n");

    const scenario = {
      id: "synthetic-truncation",
      summary: "budget smaller than the changed file",
      files: { "src/huge.ts": big },
      changed: [{ path: "src/huge.ts", changedLines: [2] }],
      required: [{ path: "src/huge.ts", because: "it is the changed file" }],
      budgetTokens: 900,
    } as const;

    const squeezed = runScenario(scenario);
    const metrics = computeMetrics(scenario, squeezed);

    expect(
      squeezed.items.some((item) => item.representation === "excerpt"),
    ).toBe(true);
    expect(metrics.truncationRate).toBeGreaterThan(0);
    expect(squeezed.budget.consumed).toBeLessThanOrEqual(squeezed.budget.limit);
  });

  it("never spends past the budget, at any budget", () => {
    // The assembler is the only component that can overspend, and an overspend
    // is invisible until a provider rejects the prompt in production.
    for (const scenario of PLANNER_CORPUS) {
      for (const budget of [20, 60, 200, 1_000, 100_000]) {
        const context = runScenario({ ...scenario, budgetTokens: budget });
        expect(
          `${scenario.id}@${String(budget)}: ${String(context.budget.consumed)}/${String(budget)}`,
        ).toBe(
          `${scenario.id}@${String(budget)}: ${String(Math.min(context.budget.consumed, budget))}/${String(budget)}`,
        );
      }
    }
  });

  it("similarity separates identical selections from different ones", () => {
    const baseline = contexts.get("stability-baseline");
    const shifted = contexts.get("stability-shifted");
    const unrelated = contexts.get("instructions-are-mandatory");
    expect(baseline).toBeDefined();
    if (
      baseline === undefined ||
      shifted === undefined ||
      unrelated === undefined
    )
      return;

    expect(contextSimilarity(baseline, shifted)).toBeGreaterThanOrEqual(
      MIN_STABILITY,
    );
    expect(contextSimilarity(baseline, unrelated)).toBeLessThan(MIN_STABILITY);
  });
});
