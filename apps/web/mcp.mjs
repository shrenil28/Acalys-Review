import fs from "node:fs";
const t=(await(await fetch("http://127.0.0.1:9222/json/list")).json()).find(x=>x.type==="page");
const ws=new WebSocket(t.webSocketDebuggerUrl);let id=0;const pend=new Map();const errs=[];
const send=(m,p={})=>new Promise(r=>{const i=++id;pend.set(i,r);ws.send(JSON.stringify({id:i,method:m,params:p}))});
ws.addEventListener("message",e=>{const m=JSON.parse(e.data);
 if(m.id&&pend.has(m.id)){pend.get(m.id)(m);pend.delete(m.id)}
 if(m.method==="Runtime.exceptionThrown")errs.push(m.params.exceptionDetails.exception?.description?.split("\n")[0]);});
await new Promise(r=>ws.addEventListener("open",r));
await send("Runtime.enable");await send("Page.enable");
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
const ev=async x=>(await send("Runtime.evaluate",{expression:x,returnByValue:true})).result.result.value;
await send("Page.navigate",{url:"http://localhost:5173/integrations"});await sleep(2600);
await ev(`[...document.querySelectorAll('button')].find(b=>b.textContent.trim()==='Add')?.click()`);await sleep(500);
console.log("MCP modal:", await ev(`(()=>{const d=document.querySelector('[role="dialog"]');if(!d)return 'MISSING';
 const txt=d.innerText;return {title:txt.split('\\n')[0], prefilledLabel:d.querySelector('input')?.value, radios:[...d.querySelectorAll('[role="radio"]')].map(r=>r.textContent.trim()), submit:[...d.querySelectorAll('button')].pop().textContent.trim()};})()`));
await ev(`[...document.querySelectorAll('[role="radio"]')].find(r=>r.textContent.includes('API key'))?.click()`);await sleep(300);
console.log("after API key:", await ev(`(()=>{const d=document.querySelector('[role="dialog"]');return {submit:[...d.querySelectorAll('button')].pop().textContent.trim(), hasKeyField:!!d.querySelector('input[type=password]')};})()`));
let s=await send("Page.captureScreenshot",{format:"png"});fs.writeFileSync("mcp_modal.png",Buffer.from(s.result.data,"base64"));
console.log("errors:", errs.length?errs.slice(0,2):"none");
ws.close();
